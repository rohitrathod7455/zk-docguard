import * as fs from 'fs';
import * as path from 'path';

/**
 * Script to export compiled contract ABIs and TypeScript wrappers to @zk-docguard/core
 */
async function exportArtifacts() {
  const artifactsDir = path.join(__dirname, '..', 'artifacts', 'src');
  const targetDir = path.join(__dirname, '..', '..', 'core', 'src', 'contracts');

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  const contracts = ['IssuerRegistry', 'DocumentRegistry', 'RevocationRegistry'];

  for (const name of contracts) {
    const artifactPath = path.join(artifactsDir, `${name}.sol`, `${name}.json`);
    if (fs.existsSync(artifactPath)) {
      const artifact = JSON.parse(fs.readFileSync(artifactPath, 'utf8'));
      const exportData = {
        contractName: artifact.contractName,
        abi: artifact.abi,
      };

      const outPath = path.join(targetDir, `${name}.json`);
      fs.writeFileSync(outPath, JSON.stringify(exportData, null, 2));
      console.log(`Exported ABI for ${name} -> ${outPath}`);
    } else {
      console.warn(`Artifact not found for ${name} at ${artifactPath}`);
    }
  }

  // Generate index.ts in targetDir
  const indexContent = `// Autogenerated contract exports
export { default as IssuerRegistryArtifact } from './IssuerRegistry.json';
export { default as DocumentRegistryArtifact } from './DocumentRegistry.json';
export { default as RevocationRegistryArtifact } from './RevocationRegistry.json';
`;
  fs.writeFileSync(path.join(targetDir, 'index.ts'), indexContent);
  console.log(`Generated contract export index at ${path.join(targetDir, 'index.ts')}`);
}

exportArtifacts().catch((err) => {
  console.error('Failed to export artifacts:', err);
  process.exit(1);
});
